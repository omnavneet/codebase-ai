#!/usr/bin/env bash
# Regenerates .ai/FILE_TREE.md (auto). PROJECT_MAP.md stays hand-curated.
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"; mkdir -p .ai
EX='node_modules|dist|build|target|.git|__pycache__|.pytest_cache|.next|venv|.venv|coverage'
{
  echo "# File tree (auto-generated by scripts/map.sh)"; echo
  if command -v tree >/dev/null 2>&1; then tree -L 3 -I "$EX" --dirsfirst | sed 's/^/    /'
  else find . -maxdepth 3 -not -path '*/.git/*' -not -path '*/node_modules/*' -not -path '*/dist/*' -not -path '*/build/*' -not -path '*/target/*' -not -name '*.zip' | sort | sed 's/^/    /'; fi
} > .ai/FILE_TREE.md
echo "Wrote .ai/FILE_TREE.md"
